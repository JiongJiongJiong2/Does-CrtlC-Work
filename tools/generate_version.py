"""Generate the Windows resource from app_version.py; --check detects drift."""

from pathlib import Path
import runpy
import sys

ROOT = Path(__file__).resolve().parents[1]


def resource():
    version = runpy.run_path(str(ROOT / 'app_version.py'))['APP_VERSION']
    numbers = tuple(int(part) for part in version.split('.')) + (0,)
    full = '.'.join(map(str, numbers))
    return f'''# Generated by tools/generate_version.py; edit app_version.py.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={numbers!r}, prodvers={numbers!r},
                    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
                    subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('080404B0', [
    StringStruct('CompanyName', 'Does Ctrl+C Work'),
    StringStruct('FileDescription', 'Does CtrlC Work Clipboard Feedback'),
    StringStruct('FileVersion', '{full}'),
    StringStruct('InternalName', 'DoesCtrlCWork'),
    StringStruct('OriginalFilename', 'DoesCtrlCWork.exe'),
    StringStruct('ProductName', 'Does Ctrl+C Work'),
    StringStruct('ProductVersion', '{full}')
  ])]), VarFileInfo([VarStruct('Translation', [2052, 1200])])]
)
'''


if __name__ == '__main__':
    path = ROOT / 'version.txt'
    expected = resource()
    if '--check' in sys.argv:
        sys.exit(0 if path.read_text(encoding='utf-8') == expected else 1)
    path.write_text(expected, encoding='utf-8')
